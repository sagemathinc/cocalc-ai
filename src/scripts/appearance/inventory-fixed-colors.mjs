#!/usr/bin/env node
// Read-only inventory. Classification is a review queue, not a safety verdict.
import ts from "../../packages/node_modules/typescript/lib/typescript.js";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../", import.meta.url));
const files = execFileSync("rg", ["--files", "packages"], {
  cwd: root,
  encoding: "utf8",
})
  .trim()
  .split("\n")
  .filter((p) => /\.[cm]?[jt]sx?$/.test(p) && !/\/dist\/|\.d\.ts$/.test(p));
const rows = [];
for (const file of files.sort()) {
  const source = ts.createSourceFile(
    file,
    readFileSync(root + file, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const aliases = new Set();
  const namespaces = new Set();
  let importLine;
  for (const node of source.statements) {
    if (
      !ts.isImportDeclaration(node) ||
      node.moduleSpecifier.text !== "@cocalc/util/theme"
    )
      continue;
    const bindings = node.importClause?.namedBindings;
    if (bindings && ts.isNamedImports(bindings)) {
      for (const item of bindings.elements) {
        if ((item.propertyName ?? item.name).text === "COLORS") {
          aliases.add(item.name.text);
          importLine ??=
            source.getLineAndCharacterOfPosition(node.getStart()).line + 1;
        }
      }
    } else if (bindings && ts.isNamespaceImport(bindings))
      namespaces.add(bindings.name.text);
  }
  const usages = [];
  function isPalette(node) {
    return (
      (ts.isIdentifier(node) && aliases.has(node.text)) ||
      (ts.isPropertyAccessExpression(node) &&
        ts.isIdentifier(node.expression) &&
        namespaces.has(node.expression.text) &&
        node.name.text === "COLORS")
    );
  }
  function visit(node) {
    if (
      (ts.isPropertyAccessExpression(node) ||
        ts.isElementAccessExpression(node)) &&
      isPalette(node.expression)
    ) {
      usages.push({
        line: source.getLineAndCharacterOfPosition(node.getStart()).line + 1,
        member: ts.isPropertyAccessExpression(node)
          ? node.name.text
          : node.argumentExpression.getText(source),
      });
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (!aliases.size && !usages.length) continue;
  const members = [...new Set(usages.map((u) => u.member))].sort();
  const category = /test|spec/.test(file)
    ? "Test/fixture"
    : /canvas|chart|plot|terminal|codemirror|slate|whiteboard|draw|color/.test(
          file,
        )
      ? "Renderer/content: inspect API and intent"
      : /frontend|docs/.test(file)
        ? "UI candidate: inspect paired foreground/background"
        : "Shared/backend: inspect consumers";
  rows.push({
    file,
    line: importLine ?? usages[0]?.line,
    category,
    usages,
    members,
  });
}
if (process.argv.includes("--json")) {
  console.log(JSON.stringify(rows, null, 2));
} else {
  console.log(
    `# Fixed Color Import Inventory\n\nGenerated by \`node src/scripts/appearance/inventory-fixed-colors.mjs\`.\n\n${rows.length} files; ${rows.reduce((n, r) => n + r.usages.length, 0)} member references.\n\nThese are **unreviewed candidates**, not confirmed bugs. Covers named/aliased and namespace imports of \`@cocalc/util/theme\`; not re-exports, local aliases, or raw CSS/literals. Re-run after migrations.\n\n| File | Queue | Members |\n| --- | --- | --- |`,
  );
  for (const row of rows)
    console.log(
      `| [${row.file}:${row.line}](../${row.file}#L${row.line}) | ${row.category} | ${row.members.join(", ")} |`,
    );
}
