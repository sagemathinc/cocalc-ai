export const PAIRING_PHRASE_WORDS = 4;

/** The phrase for the first bytes of a transcript hash. */
export function pairingPhrase(hash: Uint8Array): string {
  if (PAIRING_WORDS.length !== 256) {
    throw new Error("the pairing word list must have 256 words");
  }
  if (hash.length < PAIRING_PHRASE_WORDS) {
    throw new Error("the transcript hash is too short");
  }
  const words: string[] = [];
  for (let i = 0; i < PAIRING_PHRASE_WORDS; i++) {
    words.push(PAIRING_WORDS[hash[i]]);
  }
  return words.join("-");
}
